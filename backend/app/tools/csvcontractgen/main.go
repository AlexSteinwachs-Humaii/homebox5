// csvcontractgen generates the frontend API contract and registry from Go.
// Run from backend: go run ./app/tools/csvcontractgen
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"reflect"
	"sort"
	"strings"
	"time"

	"github.com/google/uuid"
	"github.com/sysadminsmedia/homebox/backend/internal/core/services/csvexports"
)

var types = map[string]reflect.Type{}

func ts(t reflect.Type) string {
	if t == reflect.TypeOf(uuid.UUID{}) || t == reflect.TypeOf(time.Time{}) {
		return "string"
	}
	switch t.Kind() {
	case reflect.Pointer:
		return ts(t.Elem()) + " | null"
	case reflect.Slice:
		return ts(t.Elem()) + "[]"
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int64:
		return "number"
	case reflect.Struct:
		types[t.Name()] = t
		return "Csv" + t.Name()
	}
	panic(t.String())
}
func main() {
	for _, t := range []reflect.Type{reflect.TypeOf(csvexports.Request{}), reflect.TypeOf(csvexports.Artifact{}), reflect.TypeOf(csvexports.RetentionSettings{})} {
		ts(t)
	}
	for n := 0; n != len(types); {
		n = len(types)
		for _, t := range types {
			for i := 0; i < t.NumField(); i++ {
				ts(t.Field(i).Type)
			}
		}
	}
	names := []string{}
	for n := range types {
		names = append(names, n)
	}
	sort.Strings(names)
	var out strings.Builder
	out.WriteString("// Code generated by backend/app/tools/csvcontractgen. DO NOT EDIT.\nimport type { CsvSourceId } from \"../../exports/source-registry.generated\";\n")
	for _, n := range names {
		t := types[n]
		fmt.Fprintf(&out, "export interface Csv%s {\n", n)
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			tag := strings.Split(f.Tag.Get("json"), ",")
			optional := ""
			if len(tag) > 1 {
				optional = "?"
			}
			fieldType := ts(f.Type)
			switch tag[0] {
			case "source":
				fieldType = "CsvSourceId"
			case "scope":
				fieldType = `"collection" | "private"`
			case "direction":
				fieldType = `"asc" | "desc"`
			case "kind":
				fieldType = `"all" | "recent" | "roots" | "children" | "hierarchy" | "eligible" | "explicit" | "snapshot"`
			case "status":
				if n == "Artifact" {
					fieldType = `"pending" | "running" | "completed" | "failed" | "deleting"`
				}
			}
			fmt.Fprintf(&out, "  %s%s: %s;\n", tag[0], optional, fieldType)
		}
		out.WriteString("}\n")
	}
	if err := os.WriteFile("../frontend/lib/api/types/csv-contracts.generated.ts", []byte(out.String()), 0644); err != nil {
		panic(err)
	}
	data, err := os.ReadFile("internal/core/services/csvexports/registry.json")
	if err != nil {
		panic(err)
	}
	var obj any
	if err = json.Unmarshal(data, &obj); err != nil {
		panic(err)
	}
	formatted, _ := json.MarshalIndent(obj, "", "  ")
	out.Reset()
	out.WriteString("// Code generated by backend/app/tools/csvcontractgen. DO NOT EDIT.\n// prettier-ignore\nexport const csvSources = ")
	out.Write(formatted)
	out.WriteString(" as const;\nexport type CsvSourceId = keyof typeof csvSources;\n")
	if err = os.WriteFile("../frontend/lib/exports/source-registry.generated.ts", []byte(out.String()), 0644); err != nil {
		panic(err)
	}
}
